-- Join Customers, Orders, and Products to see full details
SELECT 
    o.OrderID,
    c.CustomerName,
    p.ProductName,
    p.Category,
    o.Quantity,
    p.Price,
    (o.Quantity * p.Price) AS TotalAmount,
    o.OrderDate
FROM Orders o
INNER JOIN Customers c ON o.CustomerID = c.CustomerID
INNER JOIN Products p ON o.ProductID = p.ProductID;


-- Calculate total revenue generated by each product category
SELECT 
    p.Category,
    SUM(o.Quantity * p.Price) AS CategoryRevenue,
    COUNT(o.OrderID) AS TotalOrders
FROM Orders o
INNER JOIN Products p ON o.ProductID = p.ProductID
GROUP BY p.Category;


-- Find total money spent by each customer, ordered from highest to lowest
SELECT 
    c.CustomerName,
    c.City,
    SUM(o.Quantity * p.Price) AS TotalSpent
FROM Customers c
INNER JOIN Orders o ON c.CustomerID = o.CustomerID
INNER JOIN Products p ON o.ProductID = p.ProductID
GROUP BY c.CustomerName, c.City
ORDER BY TotalSpent DESC;


-- Find products that have zero orders
SELECT 
    p.ProductName,
    p.Category,
    p.Price
FROM Products p
LEFT JOIN Orders o ON p.ProductID = o.ProductID
WHERE o.OrderID IS NULL;

